import { chromium } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1060}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:5173/');
await page.getByRole('heading',{name:'Operations overview'}).waitFor();
console.log(JSON.stringify(await page.evaluate(()=>Array.from(document.querySelectorAll('.nav-group a')).slice(0,3).map(el=>({class:el.className,display:getComputedStyle(el).display,padding:getComputedStyle(el).padding,color:getComputedStyle(el).color})))));
const results=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21aa','wcag22aa']).analyze();
console.log(JSON.stringify(results.violations.map(v=>({id:v.id,nodes:v.nodes.slice(0,5).map(n=>({target:n.target,summary:n.failureSummary}))})),null,2));
await page.setViewportSize({width:390,height:844});
console.log(JSON.stringify(await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth,overflow:Array.from(document.querySelectorAll('body *')).map(e=>({tag:e.tagName,class:e.className,x:e.getBoundingClientRect().x,right:e.getBoundingClientRect().right,width:e.getBoundingClientRect().width})).filter(e=>e.right>innerWidth+1&&e.width>0).slice(0,20)})),null,2));
await browser.close();
